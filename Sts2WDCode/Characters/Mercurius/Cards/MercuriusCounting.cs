namespace Sts2WD.Sts2WDCode.Characters.Mercurius;

public sealed class MercuriusCounting() : MercuriusCard(0, CardType.Skill, CardRarity.Uncommon, TargetType.Self)
{
    public override IEnumerable<CardKeyword> CanonicalKeywords => [CardKeyword.Exhaust];

    protected override async Task OnPlay(PlayerChoiceContext context, CardPlay cardPlay)
    {
        var cards = Owner.PlayerCombatState!.Hand.Cards.ToList();
        await CardPileCmd.Add(cards, PileType.Draw, CardPilePosition.Bottom);
        await CardPileCmd.Draw(context, cards.Count, Owner);
    }
    protected override void OnUpgrade() { RemoveKeyword(CardKeyword.Exhaust); }
}
